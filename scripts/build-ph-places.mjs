// ─── node scripts/build-ph-places.mjs ─────────────────────────────────────────
// Builds the buyer's location lists from the Philippine Standard Geographic
// Code (PSGC), psgc.gitlab.io — the same source as src/data/locations.ts.
//
//   src/data/generated/phPlaces.ts         every province and city/municipality, by
//                                island group (small; part of the app)
//   src/data/generated/phBarangays.json    every barangay, by province and place
//                                (≈0.5 MB; loaded only when a buyer opens
//                                the barangay picker)
//
// Run it again to pick up PSGC changes; both files are generated, don't edit.

import { writeFileSync } from "node:fs";

const API = "https://psgc.gitlab.io/api";
const get = async (path) => {
  const res = await fetch(`${API}/${path}.json`);
  if (!res.ok) throw new Error(`${path}: ${res.status}`);
  return res.json();
};

// "City of Cabanatuan" → "Cabanatuan City", the way the app already writes
// Nueva Ecija's cities; "Del"/"De" inside a name as it is normally written.
const tidy = (name) => name
  .replace(/^City of Manila$/, "Manila")
  .replace(/^City of (.+)$/, "$1 City")
  .replace(/ (Del|De) /g, (_, w) => ` ${w.toLowerCase()} `);

const REGION_SHORT = {
  "Bangsamoro Autonomous Region in Muslim Mindanao": "BARMM",
  "MIMAROPA Region": "MIMAROPA",
  "NCR": "National Capital Region",
};
const ISLAND = { luzon: "Luzon", visayas: "Visayas", mindanao: "Mindanao" };

// Cities PSGC files under no province: Metro Manila's, and three that stand
// apart from the province around them. Each goes where a person would look.
const NO_PROVINCE = {
  "130000000": "Metro Manila",
  "Isabela City": "Basilan",
  "Cotabato City": "Maguindanao",
};

const [regions, provinces, places, barangays] = await Promise.all([
  get("regions"), get("provinces"), get("cities-municipalities"), get("barangays"),
]);
const regionName = Object.fromEntries(regions.map(r => [r.code, REGION_SHORT[r.name] ?? r.name]));

const byCode = new Map(); // province code → entry
for (const p of provinces) {
  byCode.set(p.code, { name: tidy(p.name), region: regionName[p.regionCode], island: ISLAND[p.islandGroupCode], places: [] });
}
const metro = { name: "Metro Manila", region: "National Capital Region", island: "Luzon", places: [] };
const provinceOf = (c) => {
  if (c.provinceCode) return byCode.get(c.provinceCode);
  if (NO_PROVINCE[c.regionCode] === "Metro Manila") return metro;
  const home = NO_PROVINCE[tidy(c.name)];
  const entry = [...byCode.values()].find(p => p.name === home);
  if (!entry) throw new Error(`No province for ${c.name}`);
  return entry;
};

const placeByCode = new Map(); // city/municipality code → { province, name }
for (const c of places) {
  const prov = provinceOf(c);
  const name = tidy(c.name);
  prov.places.push(name);
  placeByCode.set(c.code, { province: prov.name, name });
}

const cmp = (a, b) => a.localeCompare(b, "en");
const all = [metro, ...byCode.values()].filter(p => p.places.length);
for (const p of all) p.places.sort(cmp);
// Metro Manila first in Luzon, where most buyers are; then A to Z.
all.sort((a, b) => (a === metro ? -1 : b === metro ? 1 : cmp(a.name, b.name)));

const brgy = {};
for (const b of barangays) {
  const place = placeByCode.get(b.cityCode || b.municipalityCode);
  if (!place) continue;
  ((brgy[place.province] ??= {})[place.name] ??= []).push(b.name);
}
for (const prov of Object.values(brgy)) for (const list of Object.values(prov)) list.sort(cmp);

const header = `// ─── Philippine provinces and places ──────────────────────────────────────────
// GENERATED by scripts/build-ph-places.mjs from PSGC (psgc.gitlab.io). Do not
// edit by hand; run the script again.
//
// Where a buyer can be: every province and city/municipality, by island
// group. Farmers stay in Nueva Ecija (src/data/locations.ts). Barangays are in
// phBarangays.json, loaded only when a buyer opens that picker.
// ${all.length} provinces (Metro Manila counted as one), ${all.reduce((n, p) => n + p.places.length, 0)} cities and municipalities.
`;
const ts = `${header}
export type IslandGroup = "Luzon" | "Visayas" | "Mindanao";
export const ISLAND_GROUPS: IslandGroup[] = ["Luzon", "Visayas", "Mindanao"];

export interface PhProvince {
  name: string;
  /** Shown under the name in the picker, to tell look-alikes apart. */
  region: string;
  island: IslandGroup;
  places: string[];
}

export const PH_PROVINCES: PhProvince[] = [
${all.map(p => `  { name: ${JSON.stringify(p.name)}, region: ${JSON.stringify(p.region)}, island: ${JSON.stringify(p.island)}, places: ${JSON.stringify(p.places)} },`).join("\n")}
];
`;
writeFileSync("src/data/generated/phPlaces.ts", ts);
writeFileSync("src/data/generated/phBarangays.json", JSON.stringify(brgy));
console.log(`provinces ${all.length}, places ${all.reduce((n, p) => n + p.places.length, 0)}, barangays ${barangays.length}`);
console.log(`phPlaces.ts ${(ts.length / 1024).toFixed(0)} KB, phBarangays.json ${(JSON.stringify(brgy).length / 1024).toFixed(0)} KB`);
